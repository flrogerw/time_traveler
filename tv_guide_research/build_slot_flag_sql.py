"""Turn the manual slot assignments (data/slot_assignments.json) into SQL on show_syndication_eligibility's
daypart flags. READ-ONLY: writes files only (apply + rollback SQL, a diff CSV, and the late-night picks).

Block -> flag mapping (weekend blocks are shared, so each sets both the Saturday and Sunday flag):
  we_early_morning/we_morning/we_midday/we_afternoon/we_early_evening -> saturday_* AND sunday_*
  wd_early_morning/wd_morning/wd_late_morning/wd_noon/wd_early_afternoon/wd_after_school/wd_early_evening -> weekday_*
Late-night blocks (ln_*) have no flag column yet; they are written to slot_late_night_selections.csv only.
Shows now marked non-syndicated (no slots selected) and interstitials (School House Rock) are skipped.

    python -m tv_guide_research.build_slot_flag_sql
"""
import csv, json, os
import psycopg
from dotenv import load_dotenv

load_dotenv()
HERE = os.path.dirname(os.path.abspath(__file__))
BLOCK_FLAGS = {
    "we_early_morning": ["saturday_early_morning", "sunday_early_morning"],
    "we_morning": ["saturday_morning", "sunday_morning"],
    "we_midday": ["saturday_midday", "sunday_midday"],
    "we_afternoon": ["saturday_afternoon", "sunday_afternoon"],
    "we_early_evening": ["saturday_early_evening", "sunday_early_evening"],
    "wd_early_morning": ["weekday_early_morning"], "wd_morning": ["weekday_morning"],
    "wd_late_morning": ["weekday_late_morning"], "wd_noon": ["weekday_noon"],
    "wd_early_afternoon": ["weekday_early_afternoon"], "wd_after_school": ["weekday_after_school"],
    "wd_early_evening": ["weekday_early_evening"],
}
FLAGS = [f for fl in BLOCK_FLAGS.values() for f in fl]


def main():
    store = json.load(open(os.path.join(HERE, "data", "slot_assignments.json")))
    conn = psycopg.connect(host=os.environ["DB_HOST"], port=os.environ.get("DB_PORT", "5432"), user=os.environ["DB_USER"],
                           password=os.environ["DB_PASSWORD"], dbname=os.environ.get("DATABASE") or os.environ["DB_NAME"])
    conn.read_only = True
    cur = conn.cursor()
    cur.execute(f"""SELECT s.show_id, s.show_name, s.show_is_syndicated, e.mapped_genre, {', '.join('e.' + f for f in FLAGS)}
                    FROM shows s LEFT JOIN show_syndication_eligibility e USING (show_id)""")
    db = {r[0]: r for r in cur.fetchall()}
    conn.rollback()
    apply_, rollback, diff, late, skipped = [], [], [], [], []
    for sid, d in sorted(store.items(), key=lambda kv: db[int(kv[0])][1].lower()):
        sid = int(sid)
        row = db[sid]
        name, synd, mapped = row[1].strip(), row[2], row[3]
        late_blocks = [b for b in d["slots"] if b.startswith("ln_")]
        if late_blocks:
            late.append([sid, name, " ".join(late_blocks)])
        if not synd:
            skipped.append((sid, name, "not syndicated"))
            continue
        if mapped == "interstitial":   # School House Rock: Saturday-morning interstitial only (standing rule), flags kept
            skipped.append((sid, name, "interstitial: flags kept"))
            continue
        if mapped is None and all(v is None for v in row[4:]):
            skipped.append((sid, name, "no show_syndication_eligibility row"))
            continue
        target = {f: any(b in d["slots"] and f in fl for b, fl in BLOCK_FLAGS.items()) for f in FLAGS}
        current = dict(zip(FLAGS, row[4:]))
        changed = [f for f in FLAGS if bool(current[f]) != target[f]]
        if not changed:
            continue
        sets = lambda vals: ", ".join(f"{f} = {'TRUE' if vals[f] else 'FALSE'}" for f in changed)
        apply_.append(f"UPDATE show_syndication_eligibility SET {sets(target)} WHERE show_id = {sid};  -- {name}\n")
        rollback.append(f"UPDATE show_syndication_eligibility SET {sets({f: bool(current[f]) for f in changed})} WHERE show_id = {sid};  -- {name}\n")
        diff.append([sid, name, mapped or "", "; ".join(f"+{f}" for f in changed if target[f]),
                     "; ".join(f"-{f}" for f in changed if not target[f])])
    for fn, body in (("apply_slot_flags.sql", apply_), ("rollback_slot_flags.sql", rollback)):
        with open(os.path.join(HERE, fn), "w") as f:
            f.write("-- PROPOSAL ONLY: not applied. Generated by build_slot_flag_sql.py from the manual slot review.\nBEGIN;\n"
                    + "".join(body) + "COMMIT;\n")
    for fn, header, rows in (("slot_flag_changes.csv", ["show_id", "show_name", "mapped_genre", "turn_on", "turn_off"], diff),
                             ("slot_late_night_selections.csv", ["show_id", "show_name", "late_night_blocks"], late)):
        with open(os.path.join(HERE, fn), "w", newline="") as f:
            w = csv.writer(f); w.writerow(header); w.writerows(rows)
    on = sum(len(r[3].split("; ")) for r in diff if r[3]); off = sum(len(r[4].split("; ")) for r in diff if r[4])
    print(f"{len(store)} reviewed | {len(diff)} shows change | {on} flags ON, {off} flags OFF | {len(late)} late-night picks")
    print("skipped:", skipped)
    changed_ids = {r[0] for r in diff}
    no_day = [name for sid, d in store.items() for name in [db[int(sid)][1].strip()]
              if db[int(sid)][2] and d["slots"] and not any(not b.startswith("ln_") for b in d["slots"])]
    print("late-night-only (all daytime flags off):", no_day)


if __name__ == "__main__":
    main()
